// inlines the katex fonts PET math needs as base64 so math renders offline inside a webview
// rerun after upgrading katex: npm run build:katex-css
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const KEEP = new Set([
  'AMS-Regular',
  'Main-Regular',
  'Main-Bold',
  'Main-Italic',
  'Math-Italic',
  'Size1-Regular',
  'Size2-Regular',
  'Size3-Regular',
  'Size4-Regular',
]);

const require = createRequire(import.meta.url);
const dist = dirname(require.resolve('katex/dist/katex.min.css'));
const { version } = JSON.parse(readFileSync(join(dist, '..', 'package.json'), 'utf8'));
const css = readFileSync(join(dist, 'katex.min.css'), 'utf8');

const inlined = css.replace(/@font-face\{[^}]*\}/g, (rule) => {
  const font = rule.match(/fonts\/KaTeX_([\w-]+)\.woff2/)?.[1];
  if (!font || !KEEP.has(font)) return '';
  const base64 = readFileSync(join(dist, 'fonts', `KaTeX_${font}.woff2`)).toString('base64');
  return rule.replace(/src:[^;}]*/, `src:url(data:font/woff2;base64,${base64}) format("woff2")`);
});

writeFileSync(
  new URL('../src/math/katex-css.ts', import.meta.url),
  `// generated by scripts/build-katex-css.mjs from katex ${version} - do not edit\nexport const KATEX_CSS = ${JSON.stringify(inlined)};\n`,
);
